#!/usr/bin/env bash

set -euo pipefail

usage() {
  cat <<'EOF'
Usage:
  ./tools/run-score-stats.sh <run_manifest.txt> [--pass-threshold <float>] [--bins <int>]

Description:
  Computes standardized rollout score statistics from a run manifest generated by
  tools/task_runner.py. Output includes:
  - run id + sample size
  - mean/median
  - pass rate (score >= threshold)
  - perfect rate (score == 1.0)
  - percentile summary (min/p10/p25/p50/p75/p90/max)
  - histogram bins over score range [0, 1]

Notes:
  - This script uses ./tools/view-grade.sh to read each container's grade.
  - Missing/unreadable grades are skipped and reported.
EOF
}

if [[ $# -lt 1 ]]; then
  usage >&2
  exit 1
fi

run_file=""
pass_threshold="0.90"
histogram_bins="10"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pass-threshold)
      shift
      if [[ $# -eq 0 ]]; then
        echo "Missing value for --pass-threshold" >&2
        exit 1
      fi
      pass_threshold="$1"
      ;;
    --bins|--histogram-bins)
      shift
      if [[ $# -eq 0 ]]; then
        echo "Missing value for --bins" >&2
        exit 1
      fi
      histogram_bins="$1"
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    --)
      shift
      break
      ;;
    -*)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
    *)
      if [[ -n "$run_file" ]]; then
        echo "Unexpected extra argument: $1" >&2
        usage >&2
        exit 1
      fi
      run_file="$1"
      ;;
  esac
  shift
done

if [[ -z "$run_file" ]]; then
  echo "Missing run manifest argument." >&2
  usage >&2
  exit 1
fi

if [[ ! -f "$run_file" ]]; then
  echo "Run manifest not found: $run_file" >&2
  exit 1
fi

if ! [[ "$histogram_bins" =~ ^[1-9][0-9]*$ ]]; then
  echo "--bins must be a positive integer. Got: $histogram_bins" >&2
  exit 1
fi

tmp_scores="$(mktemp)"
tmp_failures="$(mktemp)"

cleanup() {
  rm -f "$tmp_scores" "$tmp_failures"
}
trap cleanup EXIT

while IFS= read -r raw_line; do
  container_id="${raw_line%%[[:space:]]*}"
  if [[ -z "$container_id" ]]; then
    continue
  fi

  grade_json="$(./tools/view-grade.sh "$container_id" 2>/dev/null || true)"
  if [[ -z "$grade_json" ]]; then
    echo "$container_id|view-grade-failed" >> "$tmp_failures"
    continue
  fi

  score="$(printf '%s' "$grade_json" | jq -er '.score' 2>/dev/null || true)"
  if [[ -z "$score" ]]; then
    echo "$container_id|score-missing" >> "$tmp_failures"
    continue
  fi

  printf '%s\n' "$score" >> "$tmp_scores"
done < "$run_file"

if [[ ! -s "$tmp_scores" ]]; then
  echo "No valid scores found in $run_file." >&2
  if [[ -s "$tmp_failures" ]]; then
    echo "Failed containers:" >&2
    cat "$tmp_failures" >&2
  fi
  exit 1
fi

python3 - "$run_file" "$pass_threshold" "$histogram_bins" "$tmp_failures" "$tmp_scores" <<'PY'
import math
import pathlib
import statistics
import sys


def quantile(sorted_values: list[float], p: float) -> float:
    if not sorted_values:
        raise ValueError("quantile() requires at least one value")
    if p <= 0:
        return sorted_values[0]
    if p >= 1:
        return sorted_values[-1]

    idx = (len(sorted_values) - 1) * p
    lower = math.floor(idx)
    upper = math.ceil(idx)
    if lower == upper:
        return sorted_values[lower]
    lower_weight = upper - idx
    upper_weight = idx - lower
    return sorted_values[lower] * lower_weight + sorted_values[upper] * upper_weight


run_file = pathlib.Path(sys.argv[1])
pass_threshold = float(sys.argv[2])
histogram_bins = int(sys.argv[3])
failure_path = pathlib.Path(sys.argv[4])
scores_path = pathlib.Path(sys.argv[5])

scores = [float(line.strip()) for line in scores_path.read_text().splitlines() if line.strip()]
scores.sort()

n = len(scores)
mean_value = statistics.mean(scores)
median_value = statistics.median(scores)
pass_count = sum(1 for value in scores if value >= pass_threshold)
perfect_count = sum(1 for value in scores if math.isclose(value, 1.0, rel_tol=0.0, abs_tol=1e-12))

percentiles = {
    "min": scores[0],
    "p10": quantile(scores, 0.10),
    "p25": quantile(scores, 0.25),
    "p50": quantile(scores, 0.50),
    "p75": quantile(scores, 0.75),
    "p90": quantile(scores, 0.90),
    "max": scores[-1],
}

hist_counts = [0 for _ in range(histogram_bins)]
for value in scores:
    if value <= 0:
        bin_index = 0
    elif value >= 1:
        bin_index = histogram_bins - 1
    else:
        bin_index = min(int(value * histogram_bins), histogram_bins - 1)
    hist_counts[bin_index] += 1

failure_lines = []
if failure_path.exists():
    failure_lines = [line.strip() for line in failure_path.read_text().splitlines() if line.strip()]

run_id = run_file.stem
print(f"run_file: {run_file}")
print(f"run_id: {run_id}")
print(f"N: {n}")
print(f"pass_threshold: {pass_threshold:.6f}")
print(f"mean: {mean_value:.6f}")
print(f"median: {median_value:.6f}")
print(
    "pass_rate(score>={threshold:.2f}): {count}/{total} = {fraction:.6f} ({percent:.2f}%)".format(
        threshold=pass_threshold,
        count=pass_count,
        total=n,
        fraction=pass_count / n,
        percent=(pass_count / n) * 100,
    )
)
print(
    "perfect_rate(score==1.0): {count}/{total} = {fraction:.6f} ({percent:.2f}%)".format(
        count=perfect_count,
        total=n,
        fraction=perfect_count / n,
        percent=(perfect_count / n) * 100,
    )
)
print(
    "percentiles(min/p10/p25/p50/p75/p90/max): "
    "{min:.6f}, {p10:.6f}, {p25:.6f}, {p50:.6f}, {p75:.6f}, {p90:.6f}, {max:.6f}".format(**percentiles)
)
print("histogram_bins([0,1]):")
for idx, count in enumerate(hist_counts):
    start = idx / histogram_bins
    end = (idx + 1) / histogram_bins
    right_bracket = "]" if idx == histogram_bins - 1 else ")"
    fraction = count / n
    print(
        "  [{start:.2f}, {end:.2f}{right}: {count} ({percent:.2f}%)".format(
            start=start,
            end=end,
            right=right_bracket,
            count=count,
            percent=fraction * 100,
        )
    )

if failure_lines:
    print(f"skipped_containers: {len(failure_lines)}")
    print("skipped_details:")
    for line in failure_lines:
        print(f"  - {line}")
PY
