def detect_tpu_devices() -> list[str]:
    """Detect available TPU devices on the host system.

    Returns empty list if TPU devices are not available.
    Supports both /dev/accel* devices (v2-v4 TPUs) and VFIO devices (v5 TPUs).
    """
    vfio_dir = Path("/dev/vfio")
    vfio_main = vfio_dir / "vfio"
    has_vfio_main = vfio_main.exists()

    # Check for v2-v4 TPU accelerator devices (/dev/accel0, /dev/accel1, etc.)
    accel_dir = Path("/dev")
    accel_devices = [f"{device_path}:{device_path}:rwm"
                     for device_path in accel_dir.glob("accel[0-9]*")
                     if device_path.is_char_device()]

    # Check for v5 TPU VFIO devices (/dev/vfio/0, /dev/vfio/1, etc.)
    vfio_devices = []
    if vfio_dir.exists():
        vfio_devices = [f"{device_path}:{device_path}:rwm"
                       for device_path in vfio_dir.glob("[0-9]*")]

    # v2-v4 TPUs: need both /dev/vfio/vfio and /dev/accel*
    if has_vfio_main and accel_devices:
        return [f"{vfio_main}:{vfio_main}:rwm"] + accel_devices

    # v5 TPUs: need /dev/vfio/vfio and /dev/vfio/[0-9]*
    if has_vfio_main and vfio_devices:
        return [f"{vfio_main}:{vfio_main}:rwm"] + vfio_devices

    return []


def generate_tpu_env_config(script_dir: Path, has_tpu: bool) -> None:
    """Generate TPU environment configuration file for Docker builds.

    If TPU devices are present, queries the GCE metadata server to get TPU
    configuration and writes environment variables to docker/tpu-env.sh.
    If no TPU devices, creates a minimal placeholder file.

    Args:
        script_dir: Root directory of the project
        has_tpu: Whether TPU devices were detected on the host

    Raises:
        RuntimeError: If TPU is present but metadata server is not accessible
                     or returns invalid data
    """
    output_file = script_dir / "docker" / "tpu-env.sh"

    if not has_tpu:
        # No TPU detected - create minimal placeholder file
        placeholder = "# No TPU devices detected on host\n# This is a placeholder file\n"
        output_file.write_text(placeholder)
        print(f"No TPU detected - generated placeholder config at {output_file}")
        return

    # TPU detected - fetch metadata (crash if this fails since we expect it to work)
    try:
        result = subprocess.run(
            ["curl", "-sf", "-m", "2",
             "http://metadata.google.internal/computeMetadata/v1/instance/attributes/tpu-env",
             "-H", "Metadata-Flavor: Google"],
            capture_output=True,
            text=True,
            timeout=3,
            check=True
        )
    except (subprocess.TimeoutExpired, subprocess.CalledProcessError) as e:
        raise RuntimeError(f"TPU devices detected but failed to fetch metadata from server: {e}")

    if not result.stdout:
        raise RuntimeError("Metadata server returned empty response")

    # Parse YAML response
    try:
        metadata = yaml.safe_load(result.stdout)
    except yaml.YAMLError as e:
        raise RuntimeError(f"Failed to parse TPU metadata as YAML: {e}")

    if not isinstance(metadata, dict):
        raise RuntimeError(f"Expected YAML dict from metadata server, got: {type(metadata)}")

    # Extract required fields and build environment file
    config_lines = [
        "# TPU configuration from GCE metadata server\n",
        "# This file is sourced to set environment variables for torch_xla\n",
        "# Generated by task_runner.py\n\n"
    ]

    # Map metadata keys to torch_xla environment variables
    if "ACCELERATOR_TYPE" in metadata:
        config_lines.append(f"export TPU_ACCELERATOR_TYPE='{metadata['ACCELERATOR_TYPE']}'\n")
    else:
        raise RuntimeError("Missing required field 'ACCELERATOR_TYPE' in TPU metadata")

    # Process bounds (prefer TPU_PROCESS_BOUNDS, fall back to HOST_BOUNDS)
    if "TPU_PROCESS_BOUNDS" in metadata:
        config_lines.append(f"export TPU_PROCESS_BOUNDS='{metadata['TPU_PROCESS_BOUNDS']}'\n")
    elif "HOST_BOUNDS" in metadata:
        config_lines.append(f"export TPU_PROCESS_BOUNDS='{metadata['HOST_BOUNDS']}'\n")
    else:
        raise RuntimeError("Missing required field 'TPU_PROCESS_BOUNDS' or 'HOST_BOUNDS' in TPU metadata")

    # Chips per process bounds (prefer TPU_CHIPS_PER_PROCESS_BOUNDS, fall back to CHIPS_PER_HOST_BOUNDS)
    if "TPU_CHIPS_PER_PROCESS_BOUNDS" in metadata:
        config_lines.append(f"export TPU_CHIPS_PER_PROCESS_BOUNDS='{metadata['TPU_CHIPS_PER_PROCESS_BOUNDS']}'\n")
    elif "CHIPS_PER_HOST_BOUNDS" in metadata:
        config_lines.append(f"export TPU_CHIPS_PER_PROCESS_BOUNDS='{metadata['CHIPS_PER_HOST_BOUNDS']}'\n")
    else:
        raise RuntimeError("Missing required field 'TPU_CHIPS_PER_PROCESS_BOUNDS' or 'CHIPS_PER_HOST_BOUNDS' in TPU metadata")

    # Worker ID
    if "WORKER_ID" in metadata:
        config_lines.append(f"export TPU_WORKER_ID='{metadata['WORKER_ID']}'\n")
    else:
        raise RuntimeError("Missing required field 'WORKER_ID' in TPU metadata")

    # Always set these to enable offline mode
    config_lines.append("\n# Enable offline mode (skip metadata server queries in container)\n")
    config_lines.append("export TPU_SKIP_MDS_QUERY=1\n")
    config_lines.append("export TPU_WORKER_HOSTNAMES=localhost\n")

    output_file.write_text(''.join(config_lines))
    print(f"Generated TPU config at {output_file}")

def warn_available_ram(num_tasks: int, task_ram_limit: str) -> None:
    total_mem_limit = num_tasks * parse_size(task_ram_limit)
    available_mem = psutil.virtual_memory().available
    if total_mem_limit > available_mem:
        print("The total memory limit across parallel tasks "
              f"({task_ram_limit} * {num_tasks} = "
              f"{format_size(total_mem_limit)}) is more than your available "
              f"memory ({format_size(available_mem)}). Proceeding this way "
              "could cause your machine to become unresponsive. "
              "Continue? [y/N]", end="")
        response = input()
        if response.strip().lower().startswith("y"):
            return
        exit(1)

def validate_ant_key(api_key: str) -> None:
    try:
        anthropic.Anthropic(api_key=api_key).models.list(limit=1)
    except anthropic.AuthenticationError:
        print("Invalid anthropic key provided")
        exit(1)

