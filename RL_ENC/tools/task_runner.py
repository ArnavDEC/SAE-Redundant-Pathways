def build_base_image(script_dir: Path) -> None:
    """Build the base Docker image that all task images will inherit from."""
    image_name = "rl-env-base"
    dockerfile_path = script_dir / "docker" / "Dockerfile.base"

    if not dockerfile_path.exists():
        raise FileNotFoundError(f"Base Dockerfile not found at {dockerfile_path}")

    print(f"Building base image {image_name}...")
    # Build with project root as context
    # Using subprocess to avoid Docker API credential store issues
    subprocess.run(
        ["docker", "build", "-f", "docker/Dockerfile.base", "-t", image_name, "."],
        cwd=script_dir,
        stdout=subprocess.DEVNULL,
        check=True
    )


def build_task_image(task_name: str, script_dir: Path,
                     hardware_info: HardwareInfo) -> None:
    """Build task-specific Docker image with task directory as context."""
    base_image_name = f"rl-task-{task_name}-base"
    image_name = f"rl-task-{task_name}"
    taskpath = script_dir / "tasks" / task_name
    dockerfile_path = taskpath / "Dockerfile"

    if not dockerfile_path.exists():
        raise FileNotFoundError(f"Dockerfile not found for task {task_name}")

    print(f"Building image {image_name}...")
    # Build with task directory as context, merging global and task-specific
    # .dockerignore files to keep cache invalidation tighter.
    build_in_task_dir(
        ["docker", "build", "-f", "Dockerfile", "-t", base_image_name, "."],
        taskpath
    )
    if hardware_info.info_str() is not None:
        wrapper_dockerfile = f"FROM {base_image_name}\n"\
                f"ENV HARDWARE_INFO={json.dumps(hardware_info.info_str())}\n"
        # If the task dockerfile imports torch, and we have
        # accelerators, add packages for using them.
        with open(taskpath / "Dockerfile") as f:
            task_dockerfile_contents = f.read()
        if "torch" in task_dockerfile_contents:
            extra_pkgs = ["accelerate"]
            if hardware_info.has_tpu:
                extra_pkgs += ["libtpu", f"torch_xla[tpu]=={TPU_TORCH_XLA_VERSION}"]
                # torch_xla wheels are binary-coupled to torch on TPU.
                wrapper_dockerfile += (
                    "RUN uv pip install --system "
                    f"torch=={TPU_TORCH_VERSION} "
                    f"--index-url {TPU_TORCH_INDEX_URL}\n"
                )
            if hardware_info.has_gpu:
                wrapper_dockerfile += "ENV LD_LIBRARY_PATH=/usr/local/cuda/compat:$LD_LIBRARY_PATH\n"
            wrapper_dockerfile += "RUN uv pip install --system " + \
                    " ".join(extra_pkgs) + "\n"
        subprocess.run(
            ["docker", "build", "-t", image_name, "-"],
            input=wrapper_dockerfile.encode(),
            check=True
        )
    else:
        docker.APIClient().tag(base_image_name, image_name)


def image_exists(image_name: str) -> bool:
    """Return True if a Docker image with the given name exists locally."""
    try:
        docker.from_env().images.get(image_name)
        return True
    except docker.errors.ImageNotFound:
        return False
    except docker.errors.DockerException as exc:
        print(f"Warning: failed to query Docker images ({exc}); "
              f"will attempt to build {image_name}.")
        return False

def run_task(task: Task, engine: str,
             docker_rm: bool, task_timeout: int,
             mem_limit: str, cpu_limit: float,
             tpu_devices: list[str],
             gpu_slot: GpuSlot | None,
             gpu_mode: str,
             disable_hints: bool,
             api_key: str,
             ant_aux_model_name: str,
             agent_model: str | None) -> Container:
    use_oauth = not api_key
    docker_args: dict[str, Any] = {
        "network": "anthropic_only",
        "environment": {"ENGINE": engine,
                        "TASK_TIMEOUT": str(task_timeout),
                        "PLATFORM": "rl-env",
                        "ANTHROPIC_API_AUXILIARY_MODEL_NAME": ant_aux_model_name,
                        **({} if use_oauth else {"ANTHROPIC_API_KEY": api_key}),
                        **({"AGENT_MODEL": agent_model} if agent_model else {}),
                        **({param.upper(): str(val)
                            for param, val in unwrap(task.params).items()}),
                        # This constructs the DISALLOWED_TOOLS environment variable
                        # that gets passed to entrypoint.sh and used by it to setup the
                        # disallowed tools cmd args for the engine invocation.
                        # Has no behaviour if engine is not claude.
                        **({"DISALLOWED_TOOLS": ",".join(
                                unwrap(task.config).disallowed_tools_claude())})},
        "mem_limit": mem_limit,
        "nano_cpus": int(cpu_limit * (10 ** 9)),
        "volumes": {}
    }
    if use_oauth:
        creds = os.path.expanduser("~/.claude/.credentials.json")
        docker_args["volumes"][creds] = {
            "bind": "/home/model/.claude/.credentials.json", "mode": "ro"}
    if gpu_mode == "all":
        docker_args["device_requests"] = [
                docker.types.DeviceRequest(count=-1, capabilities=[["gpu"]])]
    elif gpu_mode in ("per-container", "shared") and gpu_slot is not None:
        req_kwargs = build_device_request(gpu_slot)
        docker_args["device_requests"] = [
                docker.types.DeviceRequest(**req_kwargs)]
    # Add TPU devices if available
    if tpu_devices:
        docker_args["devices"] = tpu_devices
        docker_args["ulimits"] = [
                docker.types.Ulimit(name="memlock", soft=-1, hard=-1)]
    if disable_hints:
        docker_args["environment"]["DISABLE_HINTS"] = "1"

    # Mirror the remote runner's readonly-volume layout locally: bind each MOUNTS/ subdir this problem
    # needs (per MOUNTS_CONFIG.json) at /opt/<base>/<subdir>, read-only.
    root = mounts_root(task.name)
    if root is not None:
        docker_args["volumes"].update({
            str(root / s): {"bind": posixpath.join("/opt", base.strip("/"), s), "mode": "ro"}
            for s, base in problem_subdirs(task.name, task.problem_id).items()})

    if docker_rm:
        docker_args["remove"] = True

    if task.problem_id is not None:
        command = f"/entrypoint.sh {task.problem_id}"
    else:
        command = "/entrypoint.sh"

    # GPU passthrough can make container start take 30s+; increase timeout from default 60s
    client = docker.from_env(timeout=300)
    running_container = client.containers.run(
            f"rl-task-{task.name}", detach=True,
            command=command, **docker_args)
    # Put the task name in the container so that we can easily retrieve it for
    # regrades
    putfile_container(running_container, (str(task) + "\n").encode('utf-8'),
                      Path("/taskname.txt"))
    return running_container

def run_tasks_parallel(tasks: list[Task], engine: str,
                       script_dir: Path, docker_rm: bool, max_workers: int,
                       run_name: str,
                       task_timeout: int, num_runs: int,
                       mem_limit: str, cpu_limit: float,
                       tpu_devices: list[str],
                       gpu_allocator: GpuAllocator | None,
                       gpu_mode: str,
                       disable_hints: bool,
                       api_key: str,
                       ant_aux_model_name: str,
                       agent_model: str | None) -> None:
    # Thread-safe job queue that we atomically pop from
    todo_jobs = [(task, run_index, num_runs) for task in tasks for run_index in range(1, num_runs + 1)]
    running_jobs: list[tuple[tuple[Task, int, int], Container]] = []
    finished_jobs: list[tuple[tuple[Task, int, int], Container, int, str]] = []

    runs_label = f" ({num_runs} runs each)" if num_runs > 1 else ""
    print(f"Run {run_name}: Running {len(tasks)} tasks{runs_label} = {len(todo_jobs)} total jobs (max {max_workers} parallel)")

    os.makedirs("runs/", exist_ok=True)

    def run_jobs() -> None:
        try:
            next_id_tuple = todo_jobs.pop(0)
        except IndexError:
            return # If the list of jobs todo is empty, we're done

        next_job_task = next_id_tuple[0]

        # Acquire a GPU slot if using per-container mode
        slot = None
        if gpu_allocator is not None and gpu_mode in ("per-container", "shared"):
            slot = gpu_allocator.acquire()

        try:
            container = run_task(next_job_task, engine, docker_rm, task_timeout,
                                 mem_limit, cpu_limit, tpu_devices, slot,
                                 gpu_mode, disable_hints, api_key,
                                 ant_aux_model_name, agent_model)

            with open(f"runs/{run_name}.txt", 'a') as f:
                fcntl.flock(f.fileno(), fcntl.LOCK_EX)
                print(container.short_id, file=f)

            running_jobs.append((next_id_tuple, container))
            # Don't print multiple times as we spin up to max_workers. When we're
            # finishing up jobs and there are no more left to schedule, a different
            # print_job_stats will fire lower down instead.
            if len(running_jobs) == min(max_workers, num_runs * len(tasks)):
                print_job_stats(todo_jobs, running_jobs, finished_jobs)

            # We want these in the finished_jobs queue for logging
            exit_code = container.wait()["StatusCode"]
            running_jobs.remove((next_id_tuple, container))
            grade_result = subprocess.run(["./tools/view-grade.sh", container.short_id], cwd=script_dir,
                                          text=True, capture_output=True)
            if grade_result.returncode == 0:
                try:
                    grade_str = str(json.loads(grade_result.stdout)["score"])
                except json.JSONDecodeError:
                    grade_str = "ERROR"
            else:
                grade_str = "ERROR"

            finished_jobs.append((next_id_tuple, container, exit_code, grade_str))
        finally:
            # Release GPU slot after container finishes
            if gpu_allocator is not None and slot is not None:
                gpu_allocator.release(slot)

        run_jobs()

    threads = [threading.Thread(target=run_jobs, daemon=True)
               for _ in range(min(max_workers, len(todo_jobs)))]
    for thread in threads:
        thread.start()
    signal.signal(signal.SIGINT, functools.partial(stop_in_progress, running_jobs, todo_jobs))
    for thread in threads:
        thread.join()
        print_job_stats(todo_jobs, running_jobs, finished_jobs)
    print(f"Finished all jobs in run {run_name}! "
          f"Get the final pass rate with ./tools/run-pass-rate.sh runs/{run_name}.txt")

def force_exit(signum: int, frame: FrameType | None) -> None:
    exit(1)

def stop_in_progress(running_jobs: list[tuple[tuple[Task, int, int], Container]],
                     todo_jobs: list[tuple[Task, int, int]],
                     signum: int, frame: FrameType | None) -> None:
    signal.signal(signal.SIGINT, force_exit)
    todo_jobs.clear()
    print("Stopping in-progress containers (interrupt again to cancel)", file=sys.stderr)
    with ThreadPoolExecutor() as executor:
        futures = {executor.submit(c.stop): c for _, c in running_jobs}
        for future in as_completed(futures):
            future.result()
    exit(1)


def print_job_stats(todo_jobs: list[tuple[Task, int, int]],
                    running_jobs: list[tuple[tuple[Task, int, int], Container]],
                    finished_jobs: list[tuple[tuple[Task, int, int], Container, int, str]]) -> None:
    if len(finished_jobs) > 0:
        print("Finished:")
        print(tabulate([[task.name, f"{'' if task.problem_id is None else (task.problem_id + ' ')}({run_idx}/{total_runs})", container.short_id, exit_code, grade]
                        for (task, run_idx, total_runs), container, exit_code, grade
                        in finished_jobs],
                       headers=["Task", "Problem", "Container ID", "Exit code", "Grade"],
                       tablefmt="fancy_grid"))
    if len(todo_jobs) > 0:
        print("Pending:")
        for task, run_idx, total_runs in todo_jobs:
            if task.problem_id is not None:
                print(f"{task.name} - {task.problem_id} ({run_idx}/{total_runs})")
            else:
                print(f"{task.name} ({run_idx}/{total_runs})")
    else:
        print("No jobs pending")
    print("Running:")
    print(tabulate([[task.name, f"{'' if task.problem_id is None else (task.problem_id + ' ')}({run_idx}/{total_runs})", container.short_id]
                    for (task, run_idx, total_runs), container in running_jobs],
                   headers=["Task", "Problem", "Container ID"],
                   tablefmt="fancy_grid"))

def just_build(args: argparse.Namespace) -> None:
    root_dir = repo_root()
    # Detect accelerators
    tpu_devices = detect_tpu_devices()
    has_gpu = os.path.exists("/dev/nvidia0")

    tasks = [Task(name) for name in {task.name for task in args.tasks}]
    for task in tasks:
        task.load_config_and_params(root_dir)

    # Fetch artifacts before the (slow) builds so a missing record or store
    # auth failure surfaces immediately
    fetch_task_artifacts(tasks, root_dir, args.clear_stale_artifacts)

    build_base_image(root_dir)

    for task in tasks:
        build_task_image(task.name, root_dir,
                         HardwareInfo(has_tpu=bool(tpu_devices),
                                      has_gpu=has_gpu,
                                      gpu_details=None))

def run_tasks(args: argparse.Namespace) -> int:
    root_dir = repo_root()

    tasks = expand_and_validate_tasks(args.tasks, root_dir)
    assert len(tasks) > 0
    warn_available_ram(min(args.threads, len(tasks) * args.runs), args.mem_limit)

    # Validate all tasks exist
    missing_tasks = [task for task in tasks
                     if not (special_file(root_dir / "tasks" / task.name / "TASK.py").exists() or
                             special_file(root_dir / "tasks" / task.name / "TASK.txt").exists())]
    if len(missing_tasks) > 0:
        print(f"Error: Task(s) not found: {[task.name for task in missing_tasks]}")
        return 1

    for task in tasks:
        task.load_config_and_params(root_dir)

    use_oauth = args.oauth or "ANTHROPIC_API_KEY" not in os.environ
    if use_oauth:
        api_key = ""
        networked = [t.name for t in tasks if unwrap(t.config).requires_network]
        if networked:
            print("Error: oauth mode has no API key for model-calling graders; "
                  f"these tasks need one (network: true): {networked}")
            return 1
    else:
        api_key = os.environ["ANTHROPIC_API_KEY"]
        validate_ant_key(api_key)
    write_internal_claude_json(root_dir, api_key)

    # Detect TPU devices and generate environment config
    tpu_devices = detect_tpu_devices()
    generate_tpu_env_config(root_dir, has_tpu=bool(tpu_devices))

    has_gpu = os.path.exists("/dev/nvidia0")

    # Resolve GPU mode
    gpu_mode = args.gpu_mode
    if gpu_mode is None:
        gpu_mode = "all" if has_gpu else "none"

    # Build GPU allocator for per-container mode
    num_jobs = len(tasks) * args.runs
    effective_parallelism = min(args.threads, num_jobs)

    gpu_allocator: GpuAllocator | None = None
    gpu_details: str | None = None
    if gpu_mode in ("per-container", "shared"):
        if args.gpus:
            # Explicit specs: use as-is
            gpu_allocator = GpuAllocator.from_specs(parse_gpu_specs(args.gpus))
        else:
            # Auto-detect
            gpu_info = detect_gpu_info()
            if not gpu_info.gpu_indices:
                print(f"Error: --gpu-mode {gpu_mode} requested but no GPUs "
                      "detected via nvidia-smi.")
                return 1
            if gpu_mode == "shared":
                # Round-robin jobs across GPUs, multiple containers per GPU
                slots = allocate_shared_slots(gpu_info, effective_parallelism)
            else:
                # Isolated: one slot per GPU/MIG, excess jobs queue
                slots = auto_allocate_slots(gpu_info, effective_parallelism)
            if not slots:
                print(f"Error: --gpu-mode {gpu_mode} requested but could not "
                      "allocate any GPU slots.")
                return 1
            gpu_allocator = GpuAllocator(slots)
            # Explain the allocation decision
            if gpu_mode == "shared":
                print(f"GPU allocation: {effective_parallelism} job(s) shared "
                      f"across {len(gpu_info.non_mig_gpus or gpu_info.gpu_indices)} "
                      f"GPU(s)")
            elif gpu_info.has_mig and effective_parallelism > len(gpu_info.non_mig_gpus):
                print(f"GPU allocation: {gpu_info.total_migs} MIG instances "
                      f"across {len(gpu_info.mig_by_gpu)} GPU(s) → "
                      f"{gpu_allocator.num_slots} slot(s) "
                      f"(MIGs within each slot are on the same physical GPU)")
            else:
                print(f"GPU allocation: {gpu_info.total_gpus} GPU(s) → "
                      f"{gpu_allocator.num_slots} slot(s) for "
                      f"{effective_parallelism} parallel job(s)")
        print(f"GPU slots: {gpu_allocator}")
        if gpu_allocator.num_slots == 1:
            gpu_details = "1 dedicated GPU slot"
        else:
            gpu_details = (f"1 of {gpu_allocator.num_slots} GPU slots "
                          f"(round-robin)")
    elif gpu_mode == "all" and has_gpu:
        gpu_details = "all GPUs (shared)"

    for task in tasks:
        assert task.config
        if task.config.requires_accelerator and \
                not has_gpu and not tpu_devices:
            print(f"Task {task} requires an accelerator, but no gpu or tpu "
                   "found on the current machine!")
            exit(1)
        if remote_only := task.config.remote_problem.keys() | task.config.remote_job.keys():
            print(f"WARNING: {task}'s remote_problem/remote_job config is remote-only, "
                  f"so it is not applied here: {', '.join(sorted(remote_only))}")

    hardware_info = HardwareInfo(has_tpu=bool(tpu_devices),
                                 has_gpu=has_gpu and gpu_mode != "none",
                                 gpu_details=gpu_details)

    # Fetch artifacts before the (slow) builds so a missing record or store
    # auth failure surfaces immediately
    fetch_task_artifacts(tasks, root_dir, args.clear_stale_artifacts)

    # Resolve mounts before splitting into worker threads so we can error if one is missing
    for task in tasks:
        mounts_root(task.name)

    # Build the base image first (all task images depend on it)
    if args.skip_build:
        print("Skipping image builds (--skip-build). "
              "Existing images will be reused when present.")
        if not image_exists("rl-env-base"):
            print("Warning: --skip-build requested but base image rl-env-base "
                  "not found; building it now.")
            build_base_image(root_dir)
    else:
        build_base_image(root_dir)

    deduped_task_names = list({task.name for task in tasks})
    for task_name in deduped_task_names:
        image_name = f"rl-task-{task_name}"
        if args.skip_build:
            if image_exists(image_name):
                continue
            print(f"Warning: --skip-build requested but task image {image_name} "
                  "not found; building it now.")
        build_task_image(task_name, root_dir, hardware_info)

    # The aux model name is read only by model-calling graders, which oauth
    # mode rejects above; leave it empty rather than hardcode a rotting string.
    ant_aux_model_name = "" if use_oauth else get_latest_opus_str()

    if len(tasks) == 1 and args.runs == 1:
        # For single task, acquire a slot if in per-container mode
        slot = None
        if gpu_allocator is not None and gpu_mode in ("per-container", "shared"):
            slot = gpu_allocator.acquire()
        try:
            container = run_task(
                tasks[0], args.engine,
                args.rm, args.timeout,
                args.mem_limit, args.cpu_limit,
                tpu_devices, slot, gpu_mode,
                args.no_hints, api_key, ant_aux_model_name, args.model)
            print("Waiting on container to run; "
                  f"watch progress with `./tools/watch-run.sh {container.short_id}`", file=sys.stderr)
            container.wait()
        finally:
            if gpu_allocator is not None and slot is not None:
                gpu_allocator.release(slot)
        print("Container finished! "
              f"Use `./tools/view-log.sh {container.short_id} engine` to "
              "see the rollout record or "
              f"`./tools/debug-container.sh {container.short_id}` to get a shell into "
              "the final state of the container.", file=sys.stderr)
        print(container.short_id)

    else:
        if args.run_name is None:
            run_name = datetime.now().strftime("%Y%m%dT%H%M%S")
        else:
            run_name = args.run_name
        run_tasks_parallel(
            tasks, args.engine, root_dir, args.rm,
            args.threads, run_name, args.timeout, args.runs,
            args.mem_limit, args.cpu_limit, tpu_devices,
            gpu_allocator, gpu_mode,
            args.no_hints, api_key, ant_aux_model_name, args.model
        )
    return 0


def regrade_tasks(args: argparse.Namespace) -> None:
    # See all container ids that can be started. Some of these could still be
    # containers of the wrong type, but this gives us a decent sanity check on
    # arguments.
    root_dir = repo_root()
    available_containers = [container.short_id for container in
                            docker.from_env().containers.list(all=True)]
    missing_ids: list[str] = []
    ambiguous_ids: dict[str, list[str]] = {}
    resolved_ids: dict[str, str] = {}
    for container_id in args.containers:
        matches = [available_id for available_id in available_containers
                   if available_id.startswith(container_id)]
        if len(matches) == 0:
            missing_ids.append(container_id)
        elif len(matches) > 1:
            ambiguous_ids[container_id] = matches
        else:
            resolved_ids[container_id] = matches[0]
    if len(missing_ids) > 0:
        print(f"Error: Container id(s) not found: {missing_ids}")
        return
    if len(ambiguous_ids) > 0:
        print("Error: Container id prefix is ambiguous:")
        for prefix, matches in ambiguous_ids.items():
            print(f"  {prefix}: {matches}")
        print("Provide a longer container id prefix.")
        return

    for requested_id in args.containers:
        container_id = resolved_ids[requested_id]
        # First, create a /tmp/DEBUG file on disc so that the container will
        # start in debug mode.
        container = docker.from_env().containers.get(container_id)
        putfile_container(container, b'', Path("/tmp/DEBUG"))
        # Get the name of the task we're regrading
        task_spec = Task.parse(get_container_file_contents(
                      container, Path("/taskname.txt")).decode('utf-8').strip())
        # Put the latest grader code for that task in the container
        copydir_to_container(container,
                             Path(f"{repo_root()}/tasks/{task_spec.name}/grader"),
                             Path("/"))
        # Start the container
        container.start()
        backup_exit_code, _ = container.exec_run("test -f /grader/grade.json")
        if backup_exit_code == 0:
            container.exec_run("mv /grader/grade.json /grader/grade.json.old")
            print("Backed up existing /grader/grade.json to /grader/grade.json.old")
        task_spec.load_config_and_params(root_dir)
        assert "ANTHROPIC_API_KEY" in os.environ, "Need an anthropic api key set!"
        api_key = os.environ["ANTHROPIC_API_KEY"]
        validate_ant_key(api_key)
        # Run the grader (stream output so progress is visible)
        exit_code, output_stream = container.exec_run(
            f"python3 /grader/run_grader.py {task_spec.problem_id or ''}",
            workdir="/workdir", stream=True,
            environment={"PLATFORM": "rl-env",
                         "ANTHROPIC_API_KEY": api_key})
        # stream=True, so exec_run yields a bytes iterator, never a single bytes
        # blob (docker-py's stub unions both); narrow away the bytes arm.
        assert not isinstance(output_stream, bytes)
        for chunk in output_stream:
            print(chunk.decode("utf-8"), end="", flush=True)
        print()  # ensure trailing newline
        exit_code, output = container.exec_run("cat /grader/grade.json")
        if exit_code != 0:
            print("Couldn't find grade from grader.")
        else:
            # No stream=True, so exec_run returns the output as one bytes blob
            # (docker-py's stub unions bytes | Iterator[bytes]).
            assert isinstance(output, bytes)
            output_text = output.decode("utf-8")
            try:
                output_dict = json.loads(output_text)
            except json.JSONDecodeError:
                print(output_text)
            else:
                if isinstance(output_dict, dict) and "backtrace" in output_dict:
                    print("Backtrace:")
                    print(output_dict["backtrace"])
                    metadata = {key: value for key, value in output_dict.items()
                                if key != "backtrace"}
                    if metadata:
                        print("Additional grader metadata:")
                        print(metadata)
                else:
                    print(output_dict)
        container.stop()

def add_run_arguments(parser: argparse.ArgumentParser) -> None:
    """Add the 'run' subcommand arguments to a parser.

    Extracted so run.sh can reuse this for shell completion.
    """
    tasks_arg = parser.add_argument(
        "tasks", nargs="+", help="Task name(s) to run", type=Task.parse)
    set_task_completer(tasks_arg)
    parser.add_argument("-n", "--runs", type=int, default=1,
                        help="Number of times to run each task (default: 1)")
    parser.add_argument("--rm", action="store_true",
                        help="Remove containers after execution")
    parser.add_argument("--engine", default="claude", choices=["claude", "codex"],
                        help="Engine to use (default: claude)")
    parser.add_argument("--timeout", type=int, default=3600,
                        help="Task execution timeout in seconds (default: 3600)")
    parser.add_argument("--run-name", default=None,
                        help="Optional name for this run")
    parser.add_argument("-j", "--threads", type=int, default=4,
                        help="Number of parallel threads (default: 4)")
    parser.add_argument("--mem-limit", default="32G",
                        help="Docker container memory limit (default: 32G)")
    parser.add_argument("--cpu-limit", default=6.0, type=float,
                        help="Docker container CPU limit (default: 6.0)")
    parser.add_argument("--no-hints", action="store_true")
    parser.add_argument("--oauth", action="store_true",
                        help="Authenticate the agent via the host's Claude Code "
                             "subscription (mounts ~/.claude/.credentials.json) "
                             "instead of ANTHROPIC_API_KEY")
    parser.add_argument("--gpu-mode", choices=["all", "per-container", "shared", "none"],
                        default=None,
                        help="GPU passthrough mode: 'all' gives every container "
                             "all GPUs (default if GPU detected), 'per-container' "
                             "assigns isolated GPU/MIG slots (jobs queue if not enough), "
                             "'shared' round-robins jobs across GPUs allowing "
                             "multiple containers per GPU, "
                             "'none' disables GPU passthrough")
    parser.add_argument("--gpus", default=None,
                        help="GPU devices/MIG UUIDs to use (comma-separated). "
                             "Examples: '0,1,2,3' for whole GPUs, "
                             "'MIG-xxx,MIG-yyy' for MIG instances, "
                             "'0+1,2+3' for multi-GPU slots. "
                             "Only used with --gpu-mode per-container.")
    parser.add_argument("--skip-build", action="store_true", default=False,
                        help="Skip rebuilding Docker images; build only if missing.")
    parser.add_argument("--model", default=None,
                        help="Override the Claude agent model "
                             "(default set in entrypoint.sh).")
    parser.add_argument("--clear-stale-artifacts", action="store_true",
                        help="Overwrite local artifact files that don't match "
                             "any recorded tree without prompting")
    parser.set_defaults(handler=run_tasks)


def main() -> int | None:
    """CLI entrypoint."""
    parser = argparse.ArgumentParser(
        description="Run tasks with Claude or Codex",
    )
    subparsers = parser.add_subparsers()

    run_parser = subparsers.add_parser("run")
    add_run_arguments(run_parser)

    build_parser = subparsers.add_parser("build")
    tasks_arg = build_parser.add_argument(
        "tasks", nargs="+", help="Task name(s) to run", type=Task.parse)
    set_task_completer(tasks_arg)
    build_parser.add_argument("--clear-stale-artifacts", action="store_true",
                              help="Overwrite local artifact files that don't match "
                                   "any recorded tree without prompting")
    build_parser.set_defaults(handler=just_build)


    regrade_parser = subparsers.add_parser("regrade")
    regrade_parser.add_argument("containers", nargs="+", help="Task name(s) to run")
    regrade_parser.add_argument("-j", "--threads", type=int, default=4,
                                help="Number of parallel jobs (default: 4)")
    regrade_parser.set_defaults(handler=regrade_tasks)

    argcomplete.autocomplete(parser)
    args = parser.parse_args()

    # Check Docker permissions after argcomplete (don't check during tab completion)
    check_docker_permissions()

    result = args.handler(args)
    assert result is None or isinstance(result, int)
    return result

if __name__ == "__main__":
    sys.exit(main())
